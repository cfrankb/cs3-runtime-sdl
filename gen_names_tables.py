#!/usr/bin/env python3
"""
gen_names_tables.py

Regenerate the NameValue tables in src/names.cpp directly from the enum /
#define declarations in the data headers, then rewrite only that section of
names.cpp.

Everything the tables reference (Color, SoundFx, BossData::Path, Tiles and the
boss flag #defines) lives in a header somewhere under src/. This script reads
those declarations and emits the matching `_N(NAME)` rows so the tables can
never drift from the source of truth. The C++ `_N` macro still lets the
compiler resolve the numeric values, so no literal numbers are baked in here.

Tables that are regenerated (all NameValue tables in names.cpp):

    kColors  <- enum Color            in color.h
    kSounds  <- enum SoundFx          in sounds.h
    kPaths   <- enum Path (BossData)  in bossdata.h
    kTiles   <- enum Tiles            in tilesdata.h
    kFlags   <- #defines FLAG_*/BOSS_FLAG_*  in bossdata.h

Only the table block is rewritten. Includes, the `_N` macro, `using
namespace BossData;`, and every resolve*()/lookup() function are left
byte-for-byte untouched.

Usage:
    python3 gen_names_tables.py [--src-dir DIR] [--check]

    --check   Print the diff / report only; do not write files.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

# Resolve paths relative to this file so the script works from any cwd.
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(HERE, "src")

# Header of the autogenerated section that replaces the old resolver comment.
GENERATED_HEADER = """// -----------------------------------------------------------------------
// NameValue tables. AUTO-GENERATED from the enum / #define declarations in
// the data headers (color.h, sounds.h, bossdata.h, tilesdata.h).
// Regenerate with:  python3 gen_names_tables.py
// Do not edit by hand -- edit the header enums/defines instead.
// -----------------------------------------------------------------------"""


# --------------------------------------------------------------------------
# Low-level lexical helpers (string/char/comment aware)
# --------------------------------------------------------------------------
def strip_line_comments(text: str) -> str:
    """Remove `// ...` line comments, ignoring // inside string/char literals."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 1 if text[j] == "\\" else 1
            out.append(text[i : j + 1])
            i = j + 1
        elif c == "'":
            j = i + 1
            while j < n and text[j] != "'":
                j += 1 if text[j] == "\\" else 1
            out.append(text[i : j + 1])
            i = j + 1
        elif c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            if j == -1:
                break
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def split_top_level_commas(body: str):
    """Split on commas that are not inside parentheses or string literals."""
    members, buf, depth, i, n = [], [], 0, 0, len(body)
    while i < n:
        c = body[i]
        if c == '"':
            j = i + 1
            while j < n and body[j] != '"':
                j += 1 if body[j] == "\\" else 1
            buf.append(body[i : j + 1])
            i = j + 1
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == "," and depth == 0:
            members.append("".join(buf))
            buf = []
            i += 1
            continue
        buf.append(c)
        i += 1
    if any(ch.strip() for ch in buf):
        members.append("".join(buf))
    return members


def find_matching_brace(text: str, open_idx: int) -> int:
    """Return the index of the `}` matching the `{` at open_idx."""
    depth = 0
    i = open_idx
    n = len(text)
    while i < n:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise ValueError("unbalanced braces")


# --------------------------------------------------------------------------
# Enum / define extraction
# --------------------------------------------------------------------------
def parse_enum(text: str, enum_name: str):
    """Return the ordered list of enumerator names for `enum <enum_name>`."""
    # Matches: enum <name>  (optional `: underlying` type)  {
    m = re.search(r"enum\s+" + re.escape(enum_name) + r"\b[^{]*\{", text)
    if not m:
        raise RuntimeError(f"enum {enum_name!r} not found")
    body_start = m.end() - 1  # position of the '{'
    body_end = find_matching_brace(text, body_start)
    body = text[body_start + 1 : body_end]
    body = strip_line_comments(body)
    names = []
    for member in split_top_level_commas(body):
        mm = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)", member)
        if mm:
            names.append(mm.group(1))
    return names


def parse_defines(text: str, prefixes):
    """Return ordered #define names starting with any of `prefixes`."""
    names = []
    for m in re.finditer(r"#define\s+([A-Za-z_][A-Za-z0-9_]*)", text):
        name = m.group(1)
        if name.startswith(prefixes):
            names.append(name)
    return names


# --------------------------------------------------------------------------
# Table generation
# --------------------------------------------------------------------------
def render_table(table_name: str, names):
    rows = "    " + ",\n    ".join(f"_N({n})" for n in names)
    return f"const NameValue {table_name}[] = {{\n{rows},\n}};"


# Table -> source mapping. `kind`: 'enum' uses `enum_name`; 'defines' uses `prefixes`.
TABLES = [
    {"table": "kColors", "file": "color.h", "kind": "enum", "enum_name": "Color"},
    {"table": "kSounds", "file": "sounds.h", "kind": "enum", "enum_name": "SoundFx"},
    {"table": "kPaths", "file": "bossdata.h", "kind": "enum", "enum_name": "Path"},
    {"table": "kTiles", "file": "tilesdata.h", "kind": "enum", "enum_name": "Tiles"},
    {"table": "kFlags", "file": "bossdata.h", "kind": "defines", "prefixes": ("FLAG_", "BOSS_FLAG_")},
]


def build_section(src_dir):
    contents = {}
    for spec in TABLES:
        path = os.path.join(src_dir, spec["file"])
        if spec["file"] not in contents:
            with open(path, "r", encoding="utf-8") as fh:
                contents[spec["file"]] = fh.read()
    lines = []
    lines.append(GENERATED_HEADER)
    lines.append("")
    for spec in TABLES:
        if spec["kind"] == "enum":
            names = parse_enum(contents[spec["file"]], spec["enum_name"])
        else:
            names = parse_defines(contents[spec["file"]], spec["prefixes"])
        lines.append(render_table(spec["table"], names))
        lines.append("")
    # Trim the trailing blank line so the section ends exactly on the last '};'.
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Section replacement in names.cpp
# --------------------------------------------------------------------------
def rewrite_names_cpp(src_dir, section, check=False):
    path = os.path.join(src_dir, "names.cpp")
    with open(path, "r", encoding="utf-8") as fh:
        original = fh.read()

    # Anchor 1: the `using namespace BossData;` line (keep everything up to and
    # including its trailing newline).
    anchor1 = "using namespace BossData;"
    idx1 = original.index(anchor1)
    head = original[: idx1 + len(anchor1) + 1]

    # Anchor 2: the first resolve/lookup function after the tables. Everything
    # from here on (lookup + all resolve* functions) is preserved verbatim.
    anchor2 = "const NameValue *lookup("
    idx2 = original.index(anchor2, idx1)
    tail = original[idx2:]

    new_content = head + "\n" + section + "\n\n" + tail

    if new_content == original:
        print(f"[ok] {path} already up to date; no changes.")
        return False

    if check:
        print(f"[check] would rewrite {len(original)} -> {len(new_content)} bytes in {path}")
        return True

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new_content)
    print(f"[wrote] {path}")
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src-dir", default=DEFAULT_SRC, help="directory containing src/ files (default: %(default)s)")
    parser.add_argument("--check", action="store_true", help="report only; do not write")
    args = parser.parse_args()

    try:
        section = build_section(args.src_dir)
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.check:
        # Show what each table would contain.
        contents = {}
        for spec in TABLES:
            with open(os.path.join(args.src_dir, spec["file"]), encoding="utf-8") as fh:
                contents[spec["file"]] = fh.read()
        for spec in TABLES:
            if spec["kind"] == "enum":
                names = parse_enum(contents[spec["file"]], spec["enum_name"])
            else:
                names = parse_defines(contents[spec["file"]], spec["prefixes"])
            print(f"  {spec['table']:8s} <- {spec['file']:12s} {len(names):3d} entries")
        rewrite_names_cpp(args.src_dir, section, check=True)
        return 0

    rewrite_names_cpp(args.src_dir, section, check=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
