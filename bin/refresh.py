#!/usr/bin/python
import glob
import ntpath
import os
import re

TAB = " " * 4

########################################################
# vanilla application


def generate_file(folder, sub_folders):
    if not os.path.isdir(folder):
        print(f"not a directory: {folder}")
        return
    excluded = ["main.cpp", "steam_helper.cpp", 'chars.cpp']

    file_path = folder + "/CMakeLists.txt"
    lines = []
    libs = []

    lines.append("# autogenerated")
    lines.append("")

    for sf in sub_folders:
        if not os.path.isdir(sf):
            print(f"not a directory {sf}")
            continue
        path = "/".join(sf.split("/")[1:])
        basename = ntpath.basename(sf)
        lib = f"{basename}_lib"
        libs.append(lib)
        lines.append(f"add_subdirectory(${{CMAKE_CURRENT_SOURCE_DIR}}/{path} {lib})")
    lines.append("")

    basename = ntpath.basename(folder)
    master_lib = f"{basename}_lib"
    lines.append(f"set(SRC_FILES")
    files = glob.glob(f"{folder}/*.cpp")
    files = sorted(files)
    for file in files:
        basename = ntpath.basename(file)
        if basename in excluded:
            continue
        lines.append(f"{TAB}{basename}")

    lines.append(")")
    lines.append("")

    lines.append(f"add_library({master_lib} STATIC ${{SRC_FILES}})")
    lines.append("")

    if libs:
        lines.append(f"target_link_libraries({master_lib}")
        for lib in libs:
            lines.append(f"{TAB}PUBLIC {lib}")
        lines.append(")")

    lines.append("")
    lines.append("# Expose sources to parent for executable")
    lines.append(
        """
set(SRC_EXPORTED_FILES "")
foreach(file ${SRC_FILES})
    list(APPEND SRC_EXPORTED_FILES "${CMAKE_CURRENT_SOURCE_DIR}/${file}")
endforeach()
set(SRC_EXPORTED_FILES ${SRC_EXPORTED_FILES} PARENT_SCOPE)
""".strip()
    )

    prefix = "../" * len(folder.split("/"))
    lines.append("")
    lines.append(
        f"""target_include_directories({master_lib} PUBLIC
    ${{CMAKE_CURRENT_SOURCE_DIR}}
    {prefix}external
    {prefix}external/SDL3/include
    {prefix}external/SDL3_mixer/include
    {prefix}external/zlib
    )
""".strip()
    )

    lines.append("")
    # zlib is a real compile+link dependency of the shared code (compression
    # in helper.cpp, Frame*.cpp, PngMagic.cpp, layer.h). Link it PUBLIC so the
    # dependency propagates to consumers (src_lib, tests) AND so CMake orders
    # libz.a after this archive in the link line, resolving the symbols.
    # Emscripten supplies its own zlib via -sUSE_ZLIB and has no zlibstatic
    # target, so skip it there.
    lines.append('if(NOT CMAKE_SYSTEM_NAME STREQUAL "Emscripten")')
    lines.append(
        f"    target_link_libraries({master_lib} PUBLIC SDL3_mixer::SDL3_mixer zlibstatic)"
    )
    lines.append("endif()")
    lines.append("")

    with open(file_path, "w") as tfile:
        tfile.write("\n".join(lines) + "\n")


################################################
# tests


def generate_tests(folder):
    """One executable per test suite in <folder>/unit; one ctest test per
    test function. The functions of a suite are the bool declarations in
    unit/t_*.h; a main_<suite>.cpp is generated into the build tree at
    generate time and linked with the suite and the shared helpers."""
    if not os.path.isdir(folder):
        print(f"not a directory: {folder}")
        return

    unit = folder + "/unit"
    if not os.path.isdir(unit):
        print(f"not a directory: {unit}")
        return

    suites = []  # (suite name, [test function names])
    for header in sorted(glob.glob(f"{unit}/t_*.h")):
        name = ntpath.basename(header)[:-2]
        with open(header) as tfile:
            tests = re.findall(r"^bool\s+(\w+)\s*\(\s*\)\s*;", tfile.read(), re.M)
        if not tests:
            continue
        if not os.path.isfile(f"{unit}/{name}.cpp"):
            print(f"missing source for suite: {name}")
            continue
        suites.append((name, tests))

    lines = []
    lines.append("# autogenerated")
    lines.append("")

    # driver and support code compiled into every suite executable
    lines.append("set(TEST_HELPERS")
    helpers = sorted(
        ntpath.basename(f)
        for f in glob.glob(f"{unit}/*.cpp")
        if not ntpath.basename(f).startswith("t_")
    )
    for helper in helpers:
        lines.append(f"{TAB}unit/{helper}")
    lines.append(")")
    lines.append("")

    lines.append(
        """
function(add_test_suite name)
    add_executable(${name} ${ARGN} ${TEST_HELPERS} ${CMAKE_CURRENT_BINARY_DIR}/main_${name}.cpp)
    # zlib is only vendored as the `zlibstatic` target on non-Emscripten
    # builds (native, MinGW, Clang/MSVC). Emscripten supplies zlib via the
    # global -sUSE_ZLIB=1 flag, where no zlibstatic target exists, so skip
    # it there to match the main app's link target (see root CMakeLists.txt).
    target_link_libraries(${name} PRIVATE src_lib SDL3::SDL3 SDL3_mixer::SDL3_mixer)
    if(NOT CMAKE_SYSTEM_NAME STREQUAL "Emscripten")
        target_link_libraries(${name} PRIVATE zlibstatic)
    endif()
    target_include_directories(${name} PRIVATE
        ${CMAKE_SOURCE_DIR}/src
        ${CMAKE_CURRENT_SOURCE_DIR}/unit
        ${CMAKE_SOURCE_DIR}/external/SDL3/include
        ${CMAKE_SOURCE_DIR}/external/SDL3_mixer/include
    )
endfunction()""".strip()
    )
    lines.append("")

    for name, tests in suites:
        lines.append(f"# --- {name} ---")
        var = name.upper() + "_TESTS"
        lines.append(f"set({var}")
        for test in tests:
            lines.append(f"{TAB}{test}")
        lines.append(")")

        main = [f'#include "{name}.h"', '#include "test_main.h"', ""]
        main.append("static const TestEntry tests[] = {")
        main += [f'    {{"{t}", {t}}},' for t in tests]
        main += [
            "};",
            "",
            "int main(int argc, char *argv[])",
            "{",
            f'    return run_suite("{name}", tests,',
            "        static_cast<int>(sizeof(tests) / sizeof(tests[0])), argc, argv);",
            "}",
        ]
        lines.append(
            'file(GENERATE OUTPUT "${CMAKE_CURRENT_BINARY_DIR}/main_'
            + name
            + '.cpp" CONTENT [['
            + "\n".join(main)
            + "]])"
        )

        lines.append(f"add_test_suite({name} unit/{name}.cpp)")
        lines.append(f"foreach(f ${{{var}}})")
        lines.append(
            f"    add_test(NAME ${{f}} COMMAND {name} ${{f}}"
            " WORKING_DIRECTORY ${CMAKE_SOURCE_DIR})"
        )
        lines.append("endforeach()")
        lines.append("")

    lines.append(f'message(STATUS "Building {len(suites)} test suites")')

    file_path = folder + "/CMakeLists.txt"
    with open(file_path, "w") as tfile:
        tfile.write("\n".join(lines) + "\n")


