#!/usr/bin/env python3
"""Generate docs/compliance/src-coverage.md: gcov line coverage per src/*.cpp.

Runs the full pipeline:
  1. configure an instrumented out-of-source build (build-cov/, disposable)
  2. build it and run ctest (aborts on failure: never record a red run)
  3. gcov every .gcda and parse "Lines executed" per src/**/*.cpp
Files not linked into a test binary are listed as "not linked". Line counts
are gcov executable lines, not physical lines; branch coverage is not measured.
"""
import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COV = ROOT / "build-cov"
OUT = ROOT / "docs" / "compliance" / "src-coverage.md"


def run(cmd, **kw):
    return subprocess.run(cmd, **kw).returncode


def main():
    if not (COV / "CMakeCache.txt").exists():
        rc = run(["cmake", "-B", "build-cov", "-DCMAKE_BUILD_TYPE=Debug",
                  "-DCMAKE_CXX_FLAGS=--coverage -O0",
                  "-DCMAKE_EXE_LINKER_FLAGS=--coverage"], cwd=ROOT)
        if rc:
            print("ERROR: coverage configure failed", file=sys.stderr)
            return 1
    if run(["cmake", "--build", "build-cov", "-j8"], cwd=ROOT):
        print("ERROR: coverage build failed", file=sys.stderr)
        return 1
    for gcda in COV.rglob("*.gcda"):
        gcda.unlink()
    if run(["ctest", "--test-dir", "build-cov"], cwd=ROOT):
        print("ERROR: tests failed; not recording coverage", file=sys.stderr)
        return 1

    cov = {}  # src-relative path -> (pct, executable lines)
    for gcda in COV.rglob("*.gcda"):
        out = subprocess.run(["gcov", "-n", gcda.name.replace(".gcda", ".gcno")],
                             cwd=gcda.parent, capture_output=True, text=True).stdout
        cur = None
        for line in out.splitlines():
            m = re.match(r"File '(.+)'", line.strip())
            if m:
                cur = m.group(1)
                continue
            m = re.match(r"Lines executed:([0-9.]+)% of (\d+)", line.strip())
            if m and cur and cur.endswith(".cpp"):
                p = cur.split("/src/")[-1] if "/src/" in cur else None
                if p:
                    key = "src/" + p
                    pct, n = float(m.group(1)), int(m.group(2))
                    if key not in cov or pct > cov[key][0]:
                        cov[key] = (pct, n)

    allcpp = sorted(str(p.relative_to(ROOT)) for p in ROOT.glob("src/**/*.cpp"))
    rows = [(f, *cov.get(f, (None, 0))) for f in allcpp]
    hit = sum(p / 100 * n for _, p, n in rows if p is not None)
    lines = sum(n for _, _, n in rows)
    total = 100 * hit / lines if lines else 0

    text = [
        "# Source line coverage (gcov)",
        "",
        f"Generated by `itools/gen_coverage.py` on {date.today().isoformat()}. "
        "Do not edit by hand. Instrumented build in `build-cov/` (disposable, "
        "never committed).",
        "",
        f"**Total: {total:.1f}% of {lines} executable lines** "
        "(files linked into `cs3-tests` only).",
        "",
        "| File | Executable lines | Line coverage |",
        "|---|---|---|",
    ]
    for f, pct, n in sorted(rows, key=lambda r: -1 if r[1] is None else -r[1]):
        cov_cell = f"{pct:.1f}%" if pct is not None else "not linked"
        lines_cell = n if pct is not None else ""
        text.append(f"| `{f}` | {lines_cell} | {cov_cell} |")
    text.append("")
    OUT.write_text("\n".join(text))
    print(f"wrote {OUT.relative_to(ROOT)}: {total:.1f}% of {lines} lines "
          f"({len(allcpp)} cpp files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
