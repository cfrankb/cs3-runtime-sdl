#!/usr/bin/env python3
"""Generate docs/compliance/src-checklist.md from the sources in src/.

Regenerates per-file SHA256 rows (change detection). Verified checkboxes
and Notes are preserved across runs: an item is only flipped by hand after
the affected suites were rebuilt and ctest passed (never bump a hash before
testing).
"""
import hashlib
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "compliance" / "src-checklist.md"

# src file -> suites that exercise it directly (tests/*.cpp includes)
COVERED = {
    "src/boss": "t_boss",
    "src/bossdata": "t_bossdata",
    "src/actor": "t_actor",
    "src/ai_path": "t_ai_path, t_actor",
    "src/assetman": "t_assetman",
    "src/names": "t_tables",
    "src/colormap": "t_tables",
    "src/layerdata": "t_tables",
    "src/tilesdata": "t_tables",
    "src/sheetdata": "t_tables",
    "src/animator": "t_animator",
    "src/parseargs": "t_parseargs",
    "src/randomz": "t_randomz",
    "src/shared/DotArray": "t_dotarray",
    "src/statedata": "t_statedata",
    "src/game_auto": "t_ifile",
    "src/game": "t_runtime, t_game",
    "src/gamemixin": "t_runtime",
    "src/gamestats": "t_gamestats",
    "src/level": "t_level",
    "src/map": "t_map*, t_runtime",
    "src/layer": "t_map*",
    "src/maparch": "t_maparch_*",
    "src/recorder": "t_recorder",
    "src/runtime": "t_runtime",
    "src/skills": "t_gamestats, t_runtime",
    "src/states": "t_states, t_stateparser",
    "src/strhelper": "t_strhelper",
    "src/shared/FileMem": "t_ifile",
    "src/shared/FileWrap": "t_ifile, t_recorder",
    "src/shared/FrameSet": "t_frameset",
    "src/shared/Frame": "t_frameset",
    "src/shared/helper": "t_runtime, t_map*",
    "src/shared/IFile": "t_ifile",
    "src/shared/ISerial": "t_ifile",
    "src/shared/PngMagic": "t_pngmagic",
}

ROW = re.compile(r"^- \[( |x)\] `([^`]+)` `([0-9a-f]+)`(.*)$")


def load_existing():
    """Preserve checkbox state and notes keyed by file path."""
    state = {}
    if OUT.exists():
        for line in OUT.read_text().splitlines():
            m = ROW.match(line)
            if m:
                state[m.group(2)] = (m.group(1).lower() == "x", m.group(4).strip())
    return state


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    files = sorted(
        p for p in (ROOT / "src").rglob("*")
        if p.is_file() and p.suffix in (".cpp", ".h")
    )
    old = load_existing()

    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                          cwd=ROOT, capture_output=True, text=True).stdout.strip()
    covered = sum(1 for f in files if f.relative_to(ROOT).with_suffix("").as_posix() in COVERED)
    verified = sum(1 for f in files
                   if old.get(f.relative_to(ROOT).as_posix(), (False, ""))[0])

    lines = [
        "<!-- autogenerated by itools/gen_compliance.py; checkboxes and notes are preserved -->",
        "",
        "# Compliance checklist - src/",
        "",
        "| Checkpoint | Value |",
        "|---|---|",
        f"| Date | {date.today().isoformat()} |",
        f"| Git HEAD | {head} |",
        f"| Files tracked | {len(files)} |",
        f"| Covered by cs3-tests | {covered} |",
        f"| Verified items | {verified} / {len(files)} |",
        "",
        "See [README](README.md) for the verification procedure.",
        "",
    ]

    for group in ("src", "src/shared", "src/shared/implementers", "src/shared/interfaces", "src/template"):
        group_files = [f for f in files if f.relative_to(ROOT).parent.as_posix() == group]
        if not group_files:
            continue
        lines += [f"## {group}/", ""]
        for f in group_files:
            rel = f.relative_to(ROOT).as_posix()
            stem = f.relative_to(ROOT).with_suffix("").as_posix()
            check = "x" if old.get(rel, (False, ""))[0] else " "
            note = old.get(rel, (False, ""))[1]
            if not note and stem in COVERED:
                cov = COVERED[stem]
                note = f"— {cov}" if cov.startswith("PARTIAL") else f"— covered by {cov}"
            lines.append(f"- [{check}] `{rel}` `{sha256(f)[:16]}` {note}".rstrip())
        lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(files)} files, {verified} verified")


if __name__ == "__main__":
    sys.exit(main())
